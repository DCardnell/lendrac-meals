export function generateFullUKMealLibrary(): MealSeed[] {
  const results: MealSeed[] = []
  const seenSlugs = new Set<string>()

  // 1. Add the 30 signature curated meals first
  for (const m of CURATED_MEALS) {
    const slug = slugify(m.title)
    seenSlugs.add(slug)
    results.push({ ...m, slug })
  }

  // 2. Generate combinatorial UK meals (~185+ additional recipes -> 215+ total!)
  for (const arch of DISH_ARCHETYPES) {
    for (const proteinKey of arch.allowedProteins) {
      const protein = PROTEINS.find((p) => p.key === proteinKey)
      if (!protein) continue

      const title = arch.titlePattern(protein.label)
      const slug = slugify(title)
      if (seenSlugs.has(slug)) continue
      seenSlugs.add(slug)

      // Merge protein ingredient(s) + archetype extra ingredients without duplicate productIds
      const ingMap = new Map<string, MealIngredientSeed>()
      ingMap.set(protein.productId, {
        productId: protein.productId,
        quantity: protein.quantity,
        displayQuantity: protein.displayQty,
      })
      if (protein.key === 'chorizo-chicken') {
        ingMap.set('chicken-thighs', {
          productId: 'chicken-thighs',
          quantity: 600,
          displayQuantity: '600g chicken thighs',
        })
      }

      for (const extra of arch.extraIngredients) {
        if (!ingMap.has(extra.productId)) {
          ingMap.set(extra.productId, extra)
        }
      }

      const category: MealSeed['category'] = protein.isVeggie ? 'Veggie & Plant' : arch.category
      const tags = protein.isVeggie ? Array.from(new Set([...arch.tags, 'Vegetarian'])) : arch.tags

      results.push({
        slug,
        title,
        description: arch.descriptionPattern(protein.label),
        cuisine: arch.cuisine,
        category,
        prepMinutes: arch.prepMinutes,
        cookMinutes: arch.cookMinutes,
        servings: 4,
        emoji: protein.emoji,
        tags,
        ingredients: Array.from(ingMap.values()),
      })
    }
  }

  return results
}
