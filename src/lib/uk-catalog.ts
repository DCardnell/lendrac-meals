export interface StorePriceEntry {
  base: number
  loyalty?: number
  stocked?: boolean
}

export type StorePriceMap = Record<SupermarketId, StorePriceEntry>

export interface CanonicalProductSeed {
  id: string
  name: string
  aisle: string
  defaultUnit: 'g' | 'ml' | 'count' | 'pack'
  packSize: number
  packLabel: string
  storePrices: StorePriceMap
}

/**
 * Helper to generate realistic UK supermarket price spreads from a baseline Aldi/Lidl price.
 * Accounts for Tesco Clubcard / Sainsbury's Nectar / Morrisons More dual pricing,
 * and allows marking specialty items as unstocked at discounters (Aldi/Lidl).
 */
function ukPrices(
  baseDiscounterPrice: number,
  options?: {
    hasClubcardDeal?: boolean
    hasNectarDeal?: boolean
    hasMoreDeal?: boolean
    discounterStocked?: boolean
  }
): StorePriceMap {
  const r = (n: number) => Math.round(n * 100) / 100
  const stockedAtDiscounter = options?.discounterStocked ?? true

  const aldiBase = r(baseDiscounterPrice)
  const lidlBase = r(baseDiscounterPrice * 1.01)
  const asdaBase = r(baseDiscounterPrice * 1.08)
  const tescoBase = r(baseDiscounterPrice * 1.16)
  const tescoClubcard = options?.hasClubcardDeal ? r(baseDiscounterPrice * 1.03) : r(baseDiscounterPrice * 1.10)
  const sainsBase = r(baseDiscounterPrice * 1.19)
  const sainsNectar = options?.hasNectarDeal ? r(baseDiscounterPrice * 1.04) : r(baseDiscounterPrice * 1.12)
  const morrisonsBase = r(baseDiscounterPrice * 1.17)
  const morrisonsMore = options?.hasMoreDeal ? r(baseDiscounterPrice * 1.06) : r(baseDiscounterPrice * 1.12)
  const ocadoBase = r(baseDiscounterPrice * 1.26)
  const waitroseBase = r(baseDiscounterPrice * 1.32)

  return {
    aldi: { base: aldiBase, stocked: stockedAtDiscounter },
    lidl: { base: lidlBase, loyalty: r(lidlBase * 0.97), stocked: stockedAtDiscounter },
    asda: { base: asdaBase, stocked: true },
    tesco: { base: tescoBase, loyalty: tescoClubcard, stocked: true },
    sainsburys: { base: sainsBase, loyalty: sainsNectar, stocked: true },
    morrisons: { base: morrisonsBase, loyalty: morrisonsMore, stocked: true },
    ocado: { base: ocadoBase, stocked: true },
    waitrose: { base: waitroseBase, stocked: true },
  }
}

